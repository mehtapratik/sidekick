import { and, eq, isNull, sql, type InferSelectModel } from 'drizzle-orm';

import { withUserLock, type RlsTx } from '@sidekick/core/db';

import type { ExplicitEntityStatus } from '../contracts/entity';
import { SYNERGY_ERROR_CODE } from '../contracts/errors';
import { entityIndex, versionLog } from '../db/schema';
import { increment } from '../db/utils';
import { currentUserId, toActorColumns, type Actor } from './actor';
import { SynergyError } from './errors';
import { recordEvent } from './outbox';

/** A row of entity_index, exactly as Drizzle returns it */
export interface EntityIndexRow extends InferSelectModel<typeof entityIndex> {}

/** What registerEntity needs to create an entity's index row */
export interface RegisterEntityPayload {
   /** The entity's id, generated by the client */
   id: string;
   /** The key of the provider that owns the entity, such as `sandbox-notes` */
   provider: string;
   /** The provider's key for the entity's type, such as `note` */
   type: string;
   /** The name shown wherever the entity is listed or linked */
   displayName: string;
   /** The entity's title, if it has one */
   title?: string;
   /** Who is creating the entity */
   actor: Actor;
}

/**
 * Creates an entity's index row. The provider calls it in the same transaction
 * that inserts its own row.
 */
export const registerEntity = withUserLock(
   async function registerEntityMutation(
      tx,
      payload: RegisterEntityPayload,
   ): Promise<EntityIndexRow> {
      const [entity] = await tx
         .insert(entityIndex)
         .values({
            id: payload.id,
            provider: payload.provider,
            type: payload.type,
            displayName: payload.displayName,
            title: payload.title,
            ...toActorColumns(payload.actor),
            userId: currentUserId,
         })
         .returning();

      // Version 1 is a version too: the log starts at creation, so the history
      // is complete without the API or the UI adding the first entry
      await tx.insert(versionLog).values({
         userId: currentUserId,
         entityId: entity.id,
         version: entity.version,
         ...toActorColumns(payload.actor),
      });

      await recordEvent(tx, {
         kind: 'entity.created',
         subjectId: entity.id,
         actor: payload.actor,
         payload: { provider: entity.provider, type: entity.type },
      });

      return entity;
   },
);

/** What saveEntityContent needs to save an edit */
export interface SaveEntityContentPayload {
   /** The id of the entity being saved */
   id: string;
   /** The content_seq the editor started from */
   baselineContentSeq: number;
   /** The author flags a version; every other save is a revision */
   bump: 'revision' | 'version';
   /** An optional note logged with a version bump */
   changeNote?: string;
   /** The entity's display name after the edit */
   displayName: string;
   /** The entity's title after the edit; leaving it out clears it */
   title?: string;
   /** Who is saving */
   actor: Actor;
}

/**
 * Saves an edit to an entity: bumps its revision or version, and logs a version bump.
 * Throws SynergyError `stale_content` if someone saved since the editor's baseline,
 * or `not_found` if the entity is deleted or never existed.
 */
export const saveEntityContent = withUserLock(
   async function saveEntityContentMutation(
      tx,
      payload: SaveEntityContentPayload,
   ): Promise<EntityIndexRow> {
      const {
         id,
         baselineContentSeq,
         bump,
         changeNote,
         displayName,
         title,
         actor,
      } = payload;
      const revision =
         bump === 'revision'
            ? increment(entityIndex.revision)
            : entityIndex.revision;
      const version =
         bump === 'version'
            ? increment(entityIndex.version)
            : entityIndex.version;
      const contentSeq = increment(entityIndex.contentSeq);

      const [updatedEntityRow] = await tx
         .update(entityIndex)
         .set({
            version,
            revision,
            contentSeq,
            displayName,
            title: title ?? null,
            editedAt: sql`now()`,
            updatedAt: sql`now()`,
            ...toActorColumns(actor),
            reason: null,
         })
         .where(
            and(
               eq(entityIndex.id, id),
               eq(entityIndex.contentSeq, baselineContentSeq),
               isNull(entityIndex.deletedAt),
            ),
         )
         .returning();

      if (!updatedEntityRow) {
         // No match: either
         // 1. the baseline from which edit was initiated has shifted (updated by another tab or device),
         // 2. entity has been deleted, or
         // 3. it never existed in first place.
         // We hold the lock, so this answer can't change before we return it.
         const [live] = await tx
            .select({ id: entityIndex.id })
            .from(entityIndex)
            .where(and(eq(entityIndex.id, id), isNull(entityIndex.deletedAt)));

         throw new SynergyError(
            live
               ? SYNERGY_ERROR_CODE.STALE_CONTENT
               : SYNERGY_ERROR_CODE.NOT_FOUND,
         );
      }

      await recordEvent(tx, {
         kind: 'entity.content_saved',
         subjectId: id,
         actor: payload.actor,
         payload: { contentSeq: updatedEntityRow.contentSeq },
      });

      if (bump === 'version') {
         await tx.insert(versionLog).values({
            userId: currentUserId,
            entityId: id,
            version: updatedEntityRow.version,
            changeNote,
            ...toActorColumns(actor),
         });
         await recordEvent(tx, {
            kind: 'entity.version_bumped',
            subjectId: id,
            actor: payload.actor,
            payload: { version: updatedEntityRow.version },
         });
      }

      return updatedEntityRow;
   },
);

/** What setEntityStatus needs to change an entity's status */
export interface SetEntityStatusPayload {
   /** The id of the entity */
   id: string;
   /** The status it moves to */
   status: ExplicitEntityStatus;
   /** Who is changing it */
   actor: Actor;
}

/**
 * Sets an entity's status to active or deprecated, and records the change.
 * A metadata write: no counter moves. Setting the status it already has
 * changes nothing and records nothing. Throws SynergyError `not_found` if the
 * entity is deleted or never existed.
 */
export const setEntityStatus = withUserLock(
   async function setEntityStatusMutation(
      tx,
      payload: SetEntityStatusPayload,
   ): Promise<EntityIndexRow> {
      const { id, status, actor } = payload;
      const current = await getEntity(tx, id, { includeDeleted: false });
      if (!current) {
         throw new SynergyError(SYNERGY_ERROR_CODE.NOT_FOUND);
      }

      if (current.status === status) {
         return current;
      }

      const [updated] = await tx
         .update(entityIndex)
         .set({
            status,
            updatedAt: sql`now()`,
            ...toActorColumns(actor),
            reason: null,
         })
         .where(eq(entityIndex.id, id))
         .returning();

      await recordEvent(tx, {
         kind: 'entity.status_changed',
         subjectId: id,
         actor,
         payload: { from: current.status, to: status },
      });

      return updated;
   },
);

/** How getEntity looks up an entity */
export interface GetEntityOptions {
   /** Also return the entity if it is a tombstone */
   includeDeleted: boolean;
}

/** Reads one entity's index row, or `undefined` if the user has none with that id */
export async function getEntity(
   tx: RlsTx,
   id: string,
   options: GetEntityOptions,
): Promise<EntityIndexRow | undefined> {
   const [entity] = await tx
      .select()
      .from(entityIndex)
      .where(
         options.includeDeleted
            ? eq(entityIndex.id, id)
            : and(eq(entityIndex.id, id), isNull(entityIndex.deletedAt)),
      );
   return entity;
}
